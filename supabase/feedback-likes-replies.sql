-- BHAAI PDFs review likes and owner replies
-- Safe additive migration: does not alter or delete existing feedback.
create table if not exists public.feedback_likes (
  id bigint generated by default as identity primary key,
  feedback_id text not null,
  visitor_id text not null,
  created_at timestamptz not null default now(),
  constraint feedback_likes_one_per_visitor unique (feedback_id, visitor_id)
);

create table if not exists public.feedback_replies (
  feedback_id text primary key,
  reply_text text not null check (char_length(reply_text) between 1 and 2000),
  admin_user_id uuid not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.feedback_likes enable row level security;
alter table public.feedback_replies enable row level security;

drop policy if exists "Public can read feedback likes" on public.feedback_likes;
create policy "Public can read feedback likes" on public.feedback_likes
  for select to anon, authenticated using (true);
drop policy if exists "Visitors can like feedback" on public.feedback_likes;
create policy "Visitors can like feedback" on public.feedback_likes
  for insert to anon, authenticated
  with check (char_length(visitor_id) between 20 and 80 and char_length(feedback_id) between 1 and 80);

drop policy if exists "Public can read feedback replies" on public.feedback_replies;
create policy "Public can read feedback replies" on public.feedback_replies
  for select to anon, authenticated using (true);
drop policy if exists "Only BHAAI admin can add replies" on public.feedback_replies;
create policy "Only BHAAI admin can add replies" on public.feedback_replies
  for insert to authenticated
  with check (auth.uid() = 'caa2a28c-5de8-441f-8032-91598f0fa242'::uuid and admin_user_id = auth.uid());
drop policy if exists "Only BHAAI admin can update replies" on public.feedback_replies;
create policy "Only BHAAI admin can update replies" on public.feedback_replies
  for update to authenticated
  using (auth.uid() = 'caa2a28c-5de8-441f-8032-91598f0fa242'::uuid)
  with check (auth.uid() = 'caa2a28c-5de8-441f-8032-91598f0fa242'::uuid and admin_user_id = auth.uid());

grant select, insert on public.feedback_likes to anon, authenticated;
grant select on public.feedback_replies to anon, authenticated;
grant insert, update on public.feedback_replies to authenticated;
grant usage, select on sequence public.feedback_likes_id_seq to anon, authenticated;
